pub fn char_to_hid_code(c: char) -> u8 {
    let key_code = match c {
        'a' | 'A' => KeyCode::A,
        'b' | 'B' => KeyCode::B,
        'c' | 'C' => KeyCode::C,
        'd' | 'D' => KeyCode::D,
        'e' | 'E' => KeyCode::E,
        'f' | 'F' => KeyCode::F,
        'g' | 'G' => KeyCode::G,
        'h' | 'H' => KeyCode::H,
        'i' | 'I' => KeyCode::I,
        'j' | 'J' => KeyCode::J,
        'k' | 'K' => KeyCode::K,
        'l' | 'L' => KeyCode::L,
        'm' | 'M' => KeyCode::M,
        'n' | 'N' => KeyCode::N,
        'o' | 'O' => KeyCode::O,
        'p' | 'P' => KeyCode::P,
        'q' | 'Q' => KeyCode::Q,
        'r' | 'R' => KeyCode::R,
        's' | 'S' => KeyCode::S,
        't' | 'T' => KeyCode::T,
        'u' | 'U' => KeyCode::U,
        'v' | 'V' => KeyCode::V,
        'w' | 'W' => KeyCode::W,
        'x' | 'X' => KeyCode::X,
        'y' | 'Y' => KeyCode::Y,
        'z' | 'Z' => KeyCode::Z,
        '1' | '!' => KeyCode::Num1,
        '2' | '@' => KeyCode::Num2,
        '3' | '#' => KeyCode::Num3,
        '4' | '$' => KeyCode::Num4,
        '5' | '%' => KeyCode::Num5,
        '6' | '^' => KeyCode::Num6,
        '7' | '&' => KeyCode::Num7,
        '8' | '*' => KeyCode::Num8,
        '9' | '(' => KeyCode::Num9,
        '0' | ')' => KeyCode::Num0,
        '\n' => KeyCode::Enter,
        '\x1b' => KeyCode::Esc,
        '\x08' => KeyCode::Backspace,
        '\t' => KeyCode::Tab,
        ' ' => KeyCode::Space,
        '-' | '_' => KeyCode::Minus,
        '=' | '+' => KeyCode::Equal,
        '[' | '{' => KeyCode::LeftBrace,
        ']' | '}' => KeyCode::RightBrace,
        '\\' | '|' => KeyCode::Backslash,
        ';' | ':' => KeyCode::Semicolon,
        '\'' | '"' => KeyCode::Apostrophe,
        '`' | '~' => KeyCode::Grave,
        ',' | '<' => KeyCode::Comma,
        '.' | '>' => KeyCode::Dot,
        '/' | '?' => KeyCode::Slash,
        _ => KeyCode::None,
    };

    key_code as u8
}

pub fn modifiers_to_hid_code(modifiers: Modifiers) -> u8 {
    let mut modifier = 0u8;
    if let Some(modif) = modifiers {
        modif.iter().for_each(|m| modifier += m.clone() as u8);
    }
    modifier
}
